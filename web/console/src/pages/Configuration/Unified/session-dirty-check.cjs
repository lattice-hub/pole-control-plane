const assert = require('node:assert/strict');
const fs = require('node:fs');
const ts = require('typescript');
const path = require('node:path');
const Module = require('node:module');
const source = fs.readFileSync(path.join(__dirname, 'sessionDirty.ts'), 'utf8');
const code = ts.transpileModule(source, { compilerOptions: { module: ts.ModuleKind.CommonJS } }).outputText;
const mod = new Module('sessionDirty');
mod._compile(code, 'sessionDirty.js');
const { hasPendingEnvironmentDraft } = mod.exports;
const definition = { content: 'same' };
const saved = JSON.stringify(definition);
const existing = { definition, saved, needsDraft: false };
const missing = { definition, saved, needsDraft: true };
assert.equal(hasPendingEnvironmentDraft([missing], x => x), true, 'missing draft must enable saving');
assert.equal(hasPendingEnvironmentDraft([{ ...missing, needsDraft: false }], x => x), false, 'successful creation clears pending');
assert.equal(hasPendingEnvironmentDraft([existing, missing], x => x), true, 'one failed environment remains pending');
assert.equal(hasPendingEnvironmentDraft([existing], () => ({ content: 'changed' })), true, 'shared edits remain pending');
const oldDraft = { content: 'Qg==', engine: 'literal', format: 'text' };
const sharedSource = { content: 'QQ==', engine: 'literal', format: 'text' };
const oldEntry = { definition: oldDraft, saved: JSON.stringify(oldDraft), needsDraft: false };
const compose = env => ({ ...env, ...sharedSource });
assert.equal(compose(oldEntry.definition).content, 'QQ==', 'editor shows shared source A');
assert.equal(hasPendingEnvironmentDraft([oldEntry], compose), true, 'old environment B must stay dirty');
assert.equal(hasPendingEnvironmentDraft([{ ...oldEntry, saved: JSON.stringify(compose(oldDraft)) }], compose), false, 'after saving source A environment is clean');
assert.equal(hasPendingEnvironmentDraft([{ definition: { engine: 'literal' }, saved: JSON.stringify({ engine: 'literal' }), needsDraft: false }], x => ({ ...x, content: '', format: '' })), false, 'omitted proto defaults compare equal');
console.log('session dirty checks: 8 passed');
